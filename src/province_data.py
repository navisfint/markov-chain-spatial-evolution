def build_adjacency_edges(only: list[str] | None = None) -> list[tuple[str, str]]:
    """返回去重后的无向邻接边列表。only 用于限定省份集合。"""
    pool = set(only) if only else set(PROVINCES)
    edges: set[tuple[str, str]] = set()
    for a, neighbors in ADJACENCY.items():
        if a not in pool:
            continue
        for b in neighbors:
            if b not in pool:
                continue
            edges.add((a, b) if a <= b else (b, a))
    return sorted(edges)


