def normalize_province(name: object) -> str | None:
    """把任意写法的省份名统一成标准名。认不出来返回 None。"""
    if name is None:
        return None
    s = str(name).strip()
    if not s:
        return None
    # 去掉全角/半角空格、换行
    s = s.replace("\u3000", "").replace("\n", "").replace("\r", "").strip()
    if s in _NAME_ALIASES:
        return _NAME_ALIASES[s]
    # 模糊匹配：包含标准名或去掉"省/市/自治区"后缀
    for std, alias in _NAME_ALIASES.items():
        if alias and (alias in s or s in alias) and len(s) >= 2:
            # 只认标准名本身出现在字符串里，避免误匹配
            if std in s:
                return std
    return None


